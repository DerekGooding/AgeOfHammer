using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.Json.Serialization;
using AgeOfHammer.Core.Data;
using AgeOfHammer.Import;

// Imports every Age of Sigmar 4th edition army from the AoS Reminders catalog into data/factions/*.json.
//
//   dotnet run --project tools/AgeOfHammer.Import -- [options]
//
//   --catalog <path|url>   catalog.json to read (default: AoS Reminders master on GitHub, cached locally)
//   --refresh              re-download the catalog even if a cached copy exists
//   --points <n>           points target for each faction's generated default army (default 1000)
//   --only <faction-id>    import just one faction (e.g. skaven)
//
// Hand corrections go in data/overrides/<faction-id>.json and are re-applied on every import (see data/overrides/README.md).

const string DefaultCatalogUrl = "https://raw.githubusercontent.com/daviseford/aos-reminders/master/data/aos4/catalog/catalog.json";

string? catalogArg = null, only = null;
bool refresh = false;
int points = 1000;
for (int i = 0; i < args.Length; i++)
{
    string arg = args[i];
    string Next() => i + 1 < args.Length ? args[++i] : throw new ArgumentException($"{arg} needs a value.");
    switch (arg)
    {
        case "--catalog": catalogArg = Next(); break;
        case "--refresh": refresh = true; break;
        case "--points": points = int.Parse(Next()); break;
        case "--only": only = Next(); break;
        default:
            Console.Error.WriteLine($"Unknown argument '{arg}'.");
            return 2;
    }
}

string dataDir = DataLoader.FindDataDirectory(Directory.GetCurrentDirectory());
string factionsDir = Path.Combine(dataDir, "factions");
string overridesDir = Path.Combine(dataDir, "overrides");

string catalogPath;
try
{
    catalogPath = await ResolveCatalog(catalogArg ?? DefaultCatalogUrl, refresh);
}
catch (Exception ex) when (ex is HttpRequestException or IOException)
{
    Console.Error.WriteLine($"Could not get the catalog: {ex.Message}");
    return 1;
}

Console.WriteLine($"Reading {catalogPath} ...");
var catalog = Catalog.Load(catalogPath);
Console.WriteLine($"Catalog generated {catalog.GeneratedAt}; points from {catalog.SeasonName}.");

var importer = new FactionImporter(catalog, points);
var writeOptions = new JsonSerializerOptions
{
    WriteIndented = true,
    PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
    DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
    Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
};

var reports = new List<FactionReport>();
int failures = 0;
foreach (var factionEntity in catalog.OfKind("faction").OrderBy(f => f.GetProperty("name").GetString()))
{
    string name = factionEntity.GetProperty("name").GetString()!;
    string id = FactionImporter.Slug(name);
    if (only != null && id != only) continue;

    var (faction, report) = importer.Import(factionEntity);
    if (faction.Warscrolls.Count == 0)
    {
        Console.WriteLine($"  {name,-26} skipped (no playable warscrolls)");
        continue;
    }

    var node = JsonSerializer.SerializeToNode(faction, writeOptions)!.AsObject();
    string overridePath = Path.Combine(overridesDir, id + ".json");
    if (File.Exists(overridePath))
    {
        try { foreach (var u in DataPatch.Apply(node, DataPatch.ParseObject(File.ReadAllText(overridePath)))) Console.Error.WriteLine($"  {name}: override matched no {u}"); }
        catch (Exception ex) when (ex is JsonException or InvalidOperationException)
        {
            Console.Error.WriteLine($"  {name}: override file {overridePath} is invalid: {ex.Message}");
            failures++;
            continue;
        }
    }

    string json = $"// GENERATED by tools/AgeOfHammer.Import from the AoS Reminders catalog ({catalog.GeneratedAt}). Do not edit:\n" +
                  $"// put corrections in data/overrides/{id}.json and re-run the importer.\n" +
                  node.ToJsonString(writeOptions) + "\n";
    try
    {
        DataLoader.ParseFaction(json); // make sure the engine can load what we wrote
    }
    catch (InvalidDataException ex)
    {
        Console.Error.WriteLine($"  {name}: generated data failed validation:\n{ex.Message}");
        failures++;
        continue;
    }
    File.WriteAllText(Path.Combine(factionsDir, id + ".json"), json, new UTF8Encoding(false));
    reports.Add(report);
    Console.WriteLine($"  {name,-26} {report.Imported,3} warscrolls, {report.Skipped.Count,2} skipped, " +
                      $"{faction.ContentGroups.Count,3} rule groups, {faction.BattleTraits.Count,2} battle traits" +
                      (File.Exists(overridePath) ? "  (+ overrides)" : ""));
}

string reportPath = Path.Combine(dataDir, "import-report.md");
File.WriteAllText(reportPath, BuildReport(catalog, reports), new UTF8Encoding(false));
Console.WriteLine($"{reports.Sum(r => r.Imported)} warscrolls in {reports.Count} factions. Report: {reportPath}");
return failures > 0 ? 1 : 0;

static async Task<string> ResolveCatalog(string source, bool refresh)
{
    if (!source.StartsWith("http", StringComparison.OrdinalIgnoreCase)) return source;
    string cacheDir = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "AgeOfHammer", "import");
    Directory.CreateDirectory(cacheDir);
    string path = Path.Combine(cacheDir, "catalog.json");
    if (File.Exists(path) && !refresh)
    {
        Console.WriteLine($"Using cached catalog from {File.GetLastWriteTime(path):yyyy-MM-dd HH:mm} (--refresh to update).");
        return path;
    }
    Console.WriteLine($"Downloading {source} ...");
    using var http = new HttpClient { Timeout = TimeSpan.FromMinutes(5) };
    http.DefaultRequestHeaders.UserAgent.ParseAdd("AgeOfHammer-Importer/1.0");
    var bytes = await http.GetByteArrayAsync(source);
    await File.WriteAllBytesAsync(path, bytes);
    return path;
}

static string BuildReport(Catalog catalog, List<FactionReport> reports)
{
    var sb = new StringBuilder();
    sb.AppendLine("# Import report");
    sb.AppendLine();
    sb.AppendLine($"Generated by `tools/AgeOfHammer.Import` from the AoS Reminders catalog ({catalog.GeneratedAt}); points from {catalog.SeasonName}.");
    sb.AppendLine("Review the assumptions below and correct them in `data/overrides/<faction-id>.json`.");
    sb.AppendLine();
    sb.AppendLine("| Faction | Imported | Skipped | Loadout assumptions | Dropped weapons |");
    sb.AppendLine("|---|---|---|---|---|");
    foreach (var r in reports)
        sb.AppendLine($"| {r.Name} | {r.Imported} | {r.Skipped.Count} | {r.Assumptions.Count} | {r.DroppedWeapons.Count} |");
    foreach (var r in reports)
    {
        if (r.Skipped.Count + r.Assumptions.Count + r.DroppedWeapons.Count == 0) continue;
        sb.AppendLine();
        sb.AppendLine($"## {r.Name}");
        foreach (var s in r.Skipped) sb.AppendLine($"- Skipped: {s}");
        foreach (var d in r.DroppedWeapons) sb.AppendLine($"- Weapon dropped: {d}");
        foreach (var a in r.Assumptions) sb.AppendLine($"- {a}");
    }
    return sb.ToString();
}
